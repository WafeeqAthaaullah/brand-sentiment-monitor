import logging
from config.settings import settings
from src.agents.sentiment_agent import FALLBACK_MODELS, get_groq_client

logger = logging.getLogger(__name__)


def generate_crisis_response(
    post_content: str,
    summary: str,
    category: str,
) -> str:
    """Generate concise executive PR talking-point draft when severity_rating >= 7.

    Args:
        post_content: Original post content.
        summary: Summary generated by the sentiment agent.
        category: Classified crisis category.

    Returns:
        Professional executive PR talking-point draft.
    """
    client = get_groq_client()

    if not client:
        return (
            "[DRAFT RESPONSE - OFFLINE FALLBACK]\n"
            f"We are actively investigating the reported issue regarding '{category}'. "
            "Our engineering and leadership teams are prioritizing a resolution immediately."
        )

    prompt = (
        "You are a Senior Corporate Communications & Crisis PR Director.\n"
        "A critical customer incident has been flagged with severe impact.\n\n"
        f"Issue Category: {category}\n"
        f"Incident Summary: {summary}\n"
        f"Original Post: {post_content}\n\n"
        "Draft a concise, empathetic, and professional executive talking point / response statement "
        "addressing the issue directly without making legal commitments or shifting blame. "
        "Keep it actionable, reassuring, and under 150 words."
    )

    models_to_try = [settings.GROQ_MODEL] + [m for m in FALLBACK_MODELS if m != settings.GROQ_MODEL]

    for model_name in models_to_try:
        try:
            response = client.chat.completions.create(
                model=model_name,
                messages=[
                    {
                        "role": "system",
                        "content": "You are a specialized PR crisis communications expert.",
                    },
                    {"role": "user", "content": prompt},
                ],
                temperature=0.3,
                max_tokens=300,
            )
            content = response.choices[0].message.content
            if content:
                return content.strip()
        except Exception as e:
            logger.warning("Groq model %s failed for response generation: %s", model_name, e)
            continue

    return (
        "[DRAFT RESPONSE - FALLBACK]\n"
        f"We are aware of the reported incident regarding {category} and are actively investigating. "
        "Our team is taking appropriate steps to address this urgently."
    )
